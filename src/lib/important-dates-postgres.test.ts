import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { importantDateReminderAt } from "./important-dates.ts";

test("Postgres important dates keep reminder projection atomic, deduplicated and owner-scoped", async () => {
  const db = new PGlite();
  try {
    await db.exec(`create schema auth; create role authenticated; create role anon; create role service_role;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
      create function public.evaorbit_is_external_oauth() returns boolean language sql stable as $$select current_setting('test.oauth',true)='yes'$$;
      grant usage on schema auth to authenticated;
      create table public.reminders(id bigint generated by default as identity primary key,user_id uuid,title text,target_type text,target_id bigint,source_type text,source_id bigint,schedule_type text,starts_at timestamptz,next_due_at timestamptz,due_has_explicit_time boolean,timezone text,note text,lead_time_minutes integer,repeat_while_overdue boolean,status text,is_active boolean,sent_at timestamptz,last_notified_at timestamptz,snoozed_until timestamptz,cancelled_at timestamptz,updated_at timestamptz default now());
      create table public.notification_deliveries(id bigint primary key,target_type text);
      insert into auth.users values('00000000-0000-0000-0000-000000000001'),('00000000-0000-0000-0000-000000000002');
      set test.uid='00000000-0000-0000-0000-000000000001'; set test.oauth='no';`);
    await db.exec(readFileSync(new URL("../../supabase/migrations/202611260001_important_dates.sql", import.meta.url),"utf8"));
    await db.exec(readFileSync(new URL("../../supabase/migrations/202611260002_important_date_categories.sql", import.meta.url),"utf8"));
    await db.exec("set role authenticated");
    const input={title:"Colored date",date:"2096-01-01",recurrence:"none",category:"Life",note:"",pinned:false,archived:false,reminder_time:null,reminder_days_before:0};
    const save=async(id:number|null,color?:string|null)=> (await db.query<{saved:{id:number;category_color:string|null}}>("select save_important_date($1,$2::jsonb) as saved",[id,JSON.stringify({...input,...(color!==undefined?{category_color:color}:{})})])).rows[0].saved;
    const first=await save(null,"#75846F"),second=await save(null);
    assert.equal(second.category_color,"#75846F");
    await save(first.id,"#718597");
    assert.equal((await save(second.id)).category_color,"#718597");
    await assert.rejects(()=>save(999999,"#897181"),/not found/);
    assert.equal((await save(second.id)).category_color,"#718597");
    await assert.rejects(()=>save(first.id,"not-a-color"),/check constraint/);
    await save(first.id,null);assert.equal((await save(second.id)).category_color,null);
    await db.exec("set test.uid='00000000-0000-0000-0000-000000000002'");
    assert.equal((await db.query("select * from important_date_categories")).rows.length,0);
    await assert.rejects(()=>save(first.id,"#897181"),/not found/);
    assert.equal((await db.query("select * from important_date_categories")).rows.length,0);
    await db.exec("set test.uid='00000000-0000-0000-0000-000000000001'; delete from important_dates");
    const inserted=await db.query<{id:number}>("insert into important_dates(title,date,recurrence,reminder_time,reminder_days_before) values('Anniversary','2096-02-29','yearly','09:30',1) returning id");
    const id=inserted.rows[0].id;
    await db.exec("reset role");
    const reminder=async()=> (await db.query<{id:number;status:string;is_active:boolean;next_due_at:Date|null;title:string}>("select * from reminders where source_id=$1",[id])).rows[0];
    assert.equal((await reminder()).next_due_at!.toISOString(),importantDateReminderAt({title:"Anniversary",date:"2096-02-29",recurrence:"yearly",category:"",note:"",pinned:false,archived:false,reminderTime:"09:30",reminderDaysBefore:1}));
    await db.exec("update reminders set status='sent',last_notified_at=now()");
    await db.exec("select refresh_important_date_reminders()");
    assert.equal((await reminder()).status,"sent");
    await db.query("update important_dates set title='Changed',pinned=true where id=$1",[id]);
    assert.equal((await reminder()).status,"sent");assert.equal((await reminder()).title,"Changed");
    await db.query("update important_dates set archived=true where id=$1",[id]);
    assert.equal((await reminder()).is_active,false);assert.equal((await reminder()).next_due_at,null);
    await db.query("update important_dates set archived=false where id=$1",[id]);
    assert.equal((await reminder()).status,"scheduled");
    assert.equal((await db.query<{count:number}>("select count(*)::integer as count from reminders")).rows[0].count,1);
    await db.exec("set role authenticated; set test.uid='00000000-0000-0000-0000-000000000002'");
    assert.equal((await db.query("select * from important_dates")).rows.length,0);
    assert.equal((await db.query("update important_dates set archived=true returning id")).rows.length,0);
    await assert.rejects(()=>db.exec("insert into important_dates(user_id,title,date) values('00000000-0000-0000-0000-000000000001','Wrong owner','2096-01-01')"),/row-level security/);
    await db.exec("set test.uid='00000000-0000-0000-0000-000000000001'; set test.oauth='yes'");
    assert.equal((await db.query("select * from important_dates")).rows.length,0);
    await assert.rejects(()=>db.exec("select refresh_important_date_reminders()"),/permission denied/);
    await db.exec("set test.oauth='no'");
    await db.query("delete from important_dates where id=$1",[id]);
    await db.exec("reset role");
    assert.equal((await reminder()).is_active,false);
    assert.equal((await reminder()).status,"cancelled");
  } finally { await db.close(); }
});
