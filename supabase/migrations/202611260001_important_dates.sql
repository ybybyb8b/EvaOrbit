-- Important dates own their reminders; saves and cancellation are atomic.
create table public.important_dates (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (length(btrim(title)) between 1 and 120),
  date date not null check (date between '0100-01-01' and '9999-12-31'),
  recurrence text not null default 'none' check (recurrence in ('none','yearly')),
  category text not null default '' check (length(category)<=40),
  note text not null default '' check (length(note)<=2000),
  pinned boolean not null default false,
  archived boolean not null default false,
  reminder_time text check (reminder_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  reminder_days_before integer not null default 0 check (reminder_days_before between 0 and 366),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.important_dates enable row level security;
create policy important_dates_owner on public.important_dates for all to authenticated
  using (user_id=auth.uid() and not (select public.evaorbit_is_external_oauth()))
  with check (user_id=auth.uid() and not (select public.evaorbit_is_external_oauth()));
grant select,insert,update,delete on public.important_dates to authenticated;
grant usage,select on sequence public.important_dates_id_seq to authenticated;
create index important_dates_user on public.important_dates(user_id,archived,date,id);

alter table public.reminders drop constraint if exists reminders_target_type_check;
alter table public.reminders add constraint reminders_target_type_check check(target_type in ('cat','cat_household','cat_food','tracker','health','subscription','task','important_date'));
alter table public.notification_deliveries drop constraint if exists notification_deliveries_target_type_check;
alter table public.notification_deliveries add constraint notification_deliveries_target_type_check check(target_type in ('cat','cat_household','cat_food','tracker','food','health','subscription','task','important_date'));
create unique index reminders_important_date_projection on public.reminders(user_id,source_id) where source_type='important_date';

create function public.sync_important_date_reminder() returns trigger language plpgsql security definer set search_path=public as $$
declare
  occurrence date; today date := (now() at time zone 'Asia/Shanghai')::date;
  year_number integer; month_number integer; day_number integer;
  scheduled timestamptz; existing public.reminders;
begin
  if TG_OP='DELETE' then
    update public.reminders set is_active=false,status='cancelled',next_due_at=null,snoozed_until=null,cancelled_at=now()
      where user_id=old.user_id and source_type='important_date' and source_id=old.id;
    return old;
  end if;
  if TG_OP='UPDATE' and new.user_id<>old.user_id then raise exception 'Cannot change important date owner'; end if;
  occurrence:=new.date;
  if new.recurrence='yearly' and occurrence<today then
    year_number:=extract(year from today); month_number:=extract(month from new.date); day_number:=extract(day from new.date);
    occurrence:=make_date(year_number,month_number,1)+least(day_number,extract(day from (make_date(year_number,month_number,1)+interval '1 month - 1 day'))::integer)-1;
    if occurrence<today then
      if year_number=9999 then occurrence:=null;
      else
        year_number:=year_number+1;
        occurrence:=make_date(year_number,month_number,1)+least(day_number,extract(day from (make_date(year_number,month_number,1)+interval '1 month - 1 day'))::integer)-1;
      end if;
    end if;
  end if;
  select * into existing from public.reminders where user_id=new.user_id and source_type='important_date' and source_id=new.id for update;
  if new.archived or new.reminder_time is null or occurrence is null or occurrence<today then
    if existing.id is not null then
      update public.reminders set is_active=false,status='cancelled',next_due_at=null,snoozed_until=null,cancelled_at=now() where id=existing.id;
    end if;
    return new;
  end if;
  scheduled:=((occurrence-new.reminder_days_before)+new.reminder_time::time) at time zone 'Asia/Shanghai';
  if existing.id is null then
    -- Do not send a newly configured reminder whose selected alert time has already passed.
    if scheduled<now() then return new; end if;
    insert into public.reminders(user_id,title,target_type,target_id,source_type,source_id,schedule_type,starts_at,next_due_at,due_has_explicit_time,timezone,note,lead_time_minutes,repeat_while_overdue,status,is_active)
      values(new.user_id,new.title,'important_date',new.id,'important_date',new.id,'one_time',scheduled,scheduled,true,'Asia/Shanghai',occurrence::text,0,false,'scheduled',true);
  elsif existing.next_due_at is distinct from scheduled or not existing.is_active then
    update public.reminders set title=new.title,starts_at=scheduled,next_due_at=case when scheduled>=now() then scheduled else null end,
      is_active=scheduled>=now(),status=case when scheduled>=now() then 'scheduled' else 'cancelled' end,note=occurrence::text,
      sent_at=null,last_notified_at=null,snoozed_until=null,cancelled_at=null,updated_at=now() where id=existing.id;
  else
    update public.reminders set title=new.title,note=occurrence::text where id=existing.id;
  end if;
  return new;
end $$;
revoke all on function public.sync_important_date_reminder() from public;
create trigger important_date_reminder after insert or update or delete on public.important_dates
  for each row execute function public.sync_important_date_reminder();

-- Called by the existing push scheduler, including when the app has not been opened.
create function public.refresh_important_date_reminders() returns void language sql security invoker set search_path=public as $$
  update public.important_dates set updated_at=updated_at where recurrence='yearly' and not archived and reminder_time is not null;
$$;
revoke all on function public.refresh_important_date_reminders() from public,authenticated,anon;
grant execute on function public.refresh_important_date_reminders() to service_role;
