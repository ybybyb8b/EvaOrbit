begin;
create table if not exists public.software_library (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check(char_length(btrim(name)) between 1 and 80),
  category text not null default '' check(char_length(category)<=24),
  platforms jsonb not null check(jsonb_typeof(platforms)='array' and jsonb_array_length(platforms) between 1 and 5 and platforms <@ '["macOS","iOS","Windows","Android","Web"]'::jsonb),
  license text not null check(license in('perpetual','version')),
  version text not null default '' check((license='perpetual' and version='') or (license='version' and char_length(btrim(version)) between 1 and 40)),
  acquisition text not null check(acquisition in('paid','giveaway','gift')),
  acquired_on date,
  website text not null default '' check(char_length(website)<=2000 and (website='' or website ~ '^https?://')),
  notes text not null default '' check(char_length(notes)<=2000),
  created_at timestamptz not null default timezone('utc',now()),
  updated_at timestamptz not null default timezone('utc',now())
);
create index if not exists idx_software_library_user_name on public.software_library(user_id,name,id);
drop trigger if exists software_library_updated_at on public.software_library;
create trigger software_library_updated_at before update on public.software_library for each row execute function public.set_updated_at();
alter table public.software_library enable row level security;
drop policy if exists software_library_owner on public.software_library;
create policy software_library_owner on public.software_library for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
revoke all on public.software_library from anon;
grant select,insert,update,delete on public.software_library to authenticated,service_role;
grant usage,select on sequence public.software_library_id_seq to authenticated,service_role;
commit;
