// Regenerate deliberately when extending the supported range; the app has no runtime calendar dependency.
import fs from "node:fs";
import lunar from "lunar-javascript";
const {Lunar,LunarYear}=lunar;
const version=JSON.parse(fs.readFileSync("node_modules/lunar-javascript/package.json","utf8")).version;
const years=[];
for(let year=1901;year<=2100;year++){
  const info=LunarYear.fromYear(year),months=info.getMonths().filter(month=>month.getYear()===year);let bits=0;
  if(months.length!==12&&months.length!==13)throw new Error("Invalid lunar year");
  months.forEach((month,index)=>{if(month.getDayCount()===30)bits|=1<<index;});
  years.push([Lunar.fromYmd(year,1,1).getSolar().toYmd(),info.getLeapMonth(),bits]);
}
if(years[2027-1901][0]!=="2027-02-06")throw new Error("2027 New Year does not match HKO");
const license=fs.readFileSync("node_modules/lunar-javascript/LICENSE","utf8");
const source=`// Generated by scripts/generate-lunar-calendar.mjs using lunar-javascript ${version}.
// Chinese lunar years 1901–2100: [Gregorian New Year date, leap month (0=none), 30-day month bitmask].
/*!
${license}
*/
export const lunarYears: readonly (readonly [string,number,number])[] = [
${years.map(row=>`  ${JSON.stringify(row)},`).join("\n")}
];
`;
fs.writeFileSync("src/lib/lunar-calendar-data.ts",source);
// Used only to create a NEW schema migration; never rewrite an applied migration.
fs.mkdirSync("tmp",{recursive:true});
fs.writeFileSync("tmp/lunar-year-values.sql",years.map(([date,leap,bits],index)=>`(${1901+index},date '${date}',${leap},${bits})`).join(",\n"));
console.log(`Generated ${years.length} lunar years`);
